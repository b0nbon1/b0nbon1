// Theme toggle functionality
(function() {
  const THEME_KEY = 'theme';
  const THEME_LIGHT = 'light';
  const THEME_DARK = 'dark';
  const THEME_SYSTEM = 'system';

  // Get the current theme from localStorage or default to system
  function getStoredTheme() {
    return localStorage.getItem(THEME_KEY) || THEME_SYSTEM;
  }

  // Get system preference
  function getSystemTheme() {
    return window.matchMedia('(prefers-color-scheme: dark)').matches ? THEME_DARK : THEME_LIGHT;
  }

  // Get the effective theme (resolve system to actual theme)
  function getEffectiveTheme(theme) {
    return theme === THEME_SYSTEM ? getSystemTheme() : theme;
  }

  // Apply theme to document
  function applyTheme(theme) {
    const effectiveTheme = getEffectiveTheme(theme);
    const html = document.documentElement;

    if (effectiveTheme === THEME_DARK) {
      html.classList.add('dark');
    } else {
      html.classList.remove('dark');
    }
  }

  // Initialize theme on page load
  function initTheme() {
    const storedTheme = getStoredTheme();
    applyTheme(storedTheme);
  }

  // Toggle between light, dark, and system
  function toggleTheme() {
    const currentTheme = getStoredTheme();
    let newTheme;

    // Cycle through: light -> dark -> system -> light
    if (currentTheme === THEME_LIGHT) {
      newTheme = THEME_DARK;
    } else if (currentTheme === THEME_DARK) {
      newTheme = THEME_SYSTEM;
    } else {
      newTheme = THEME_LIGHT;
    }

    localStorage.setItem(THEME_KEY, newTheme);
    applyTheme(newTheme);
    updateThemeButton(newTheme);
  }

  // Update theme button text
  function updateThemeButton(theme) {
    const button = document.getElementById('theme-toggle');
    if (!button) return;

    const effectiveTheme = getEffectiveTheme(theme);

    // Update button emoji based on current theme
    if (theme === THEME_SYSTEM) {
      button.textContent = effectiveTheme === THEME_DARK ? '🌙' : '☀️';
      button.title = 'Theme: System (' + (effectiveTheme === THEME_DARK ? 'Dark' : 'Light') + ')';
    } else if (theme === THEME_DARK) {
      button.textContent = '🌙';
      button.title = 'Theme: Dark';
    } else {
      button.textContent = '☀️';
      button.title = 'Theme: Light';
    }
  }

  // Listen for system theme changes
  function watchSystemTheme() {
    const mediaQuery = window.matchMedia('(prefers-color-scheme: dark)');
    mediaQuery.addEventListener('change', () => {
      const storedTheme = getStoredTheme();
      if (storedTheme === THEME_SYSTEM) {
        applyTheme(THEME_SYSTEM);
        updateThemeButton(THEME_SYSTEM);
      }
    });
  }

  // Initialize on DOM ready
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
      initTheme();
      watchSystemTheme();

      const button = document.getElementById('theme-toggle');
      if (button) {
        button.addEventListener('click', toggleTheme);
        updateThemeButton(getStoredTheme());
      }
    });
  } else {
    initTheme();
    watchSystemTheme();

    const button = document.getElementById('theme-toggle');
    if (button) {
      button.addEventListener('click', toggleTheme);
      updateThemeButton(getStoredTheme());
    }
  }

  // Expose toggle function globally for the button
  window.toggleTheme = toggleTheme;
})();
